/**
 * Deployment-surface provenance for one project (D-224).
 *
 *   pnpm facilis:env [--dir <path>] [--example]
 *
 * Loads `<dir>/facilis.config.ts`, resolves it against the real environment and prints
 * KEY | SOURCE | VALUE for the runtime block and, separately, the public block. A secret is
 * always `[redacted]`: the box is the only way to read it and this command never does.
 *
 * `--example` writes `.env.example` next to the config instead, and refuses to overwrite a
 * file whose header is not the generated one.
 *
 * Run with node --experimental-strip-types (the root script does).
 */
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import {
  ENV_EXAMPLE_HEADER,
  SecretString,
  formatRuntimeProblems,
  renderEnvExample,
  resolvePublicConfig,
  resolveRuntimeConfig,
  type FacilisConfig,
  type FacilisRuntimeValue,
  type JsonValue,
  type RuntimeConfigProblem,
  type RuntimeConfigSource,
  type RuntimeConfigSources,
} from "../packages/core/src/index.ts";

interface Options {
  readonly dir: string;
  readonly example: boolean;
}

interface Row {
  readonly key: string;
  readonly source: RuntimeConfigSource;
  readonly value: string;
}

const USAGE = [
  "Usage: pnpm facilis:env [--dir <path>] [--example]",
  "",
  "  --dir <path>  project directory containing facilis.config.ts (default: .)",
  "  --example     write .env.example next to the config instead of printing the table",
  "  --help        show this message",
].join("\n");

function parseArgs(argv: readonly string[]): Options | null {
  let dir = ".";
  let example = false;
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--help" || argument === "-h") return null;
    if (argument === "--example") {
      example = true;
      continue;
    }
    if (argument === "--dir") {
      const value = argv[index + 1];
      if (value === undefined || value.startsWith("--")) throw new Error("--dir needs a path");
      dir = value;
      index += 1;
      continue;
    }
    throw new Error(`unknown argument: ${argument ?? "?"}`);
  }
  return { dir, example };
}

async function loadConfig(configPath: string): Promise<FacilisConfig> {
  if (!existsSync(configPath)) throw new Error(`no facilis.config.ts at ${configPath}`);
  const loaded: unknown = await import(pathToFileURL(configPath).href);
  if (typeof loaded !== "object" || loaded === null || !("default" in loaded)) {
    throw new Error(`${configPath} has no default export`);
  }
  const config = (loaded as { default: unknown }).default;
  if (typeof config !== "object" || config === null) {
    throw new Error(`${configPath} does not export a config object`);
  }
  return config as FacilisConfig;
}

function cell(value: FacilisRuntimeValue | JsonValue): string {
  if (value instanceof SecretString) return "[redacted]";
  if (value === null) return "(null)";
  if (typeof value === "string") return value;
  return JSON.stringify(value);
}

function rowsFor(
  values: Readonly<Record<string, FacilisRuntimeValue>>,
  sources: RuntimeConfigSources,
): Row[] {
  return Object.entries(values)
    .map(([key, value]) => ({ key, source: sources[key] ?? "declared", value: cell(value) }))
    .toSorted((left, right) => (left.key < right.key ? -1 : left.key > right.key ? 1 : 0));
}

function renderTable(rows: readonly Row[]): string {
  if (rows.length === 0) return "(none declared)";
  const keyWidth = Math.max("KEY".length, ...rows.map((row) => row.key.length));
  const sourceWidth = Math.max("SOURCE".length, ...rows.map((row) => row.source.length));
  const header = `${"KEY".padEnd(keyWidth)}  ${"SOURCE".padEnd(sourceWidth)}  VALUE`;
  const lines = rows.map(
    (row) => `${row.key.padEnd(keyWidth)}  ${row.source.padEnd(sourceWidth)}  ${row.value}`,
  );
  return [header, ...lines].join("\n");
}

async function writeExample(target: string, config: FacilisConfig): Promise<void> {
  if (existsSync(target)) {
    const current = await readFile(target, "utf8");
    if (!current.startsWith(ENV_EXAMPLE_HEADER)) {
      throw new Error(`${target} was not generated by pnpm facilis:env; refusing to overwrite it`);
    }
  }
  await writeFile(target, renderEnvExample(config), "utf8");
}

async function main(argv: readonly string[]): Promise<number> {
  const options = parseArgs(argv);
  if (options === null) {
    console.log(USAGE);
    return 0;
  }
  const configPath = resolve(options.dir, "facilis.config.ts");
  const config = await loadConfig(configPath);

  if (options.example) {
    const target = join(dirname(configPath), ".env.example");
    await writeExample(target, config);
    console.log(target);
    return 0;
  }

  const runtime = resolveRuntimeConfig({ runtime: config.runtime, env: process.env });
  const publicConfig = resolvePublicConfig({ public: config.public, env: process.env });
  const problems: RuntimeConfigProblem[] = [...runtime.problems, ...publicConfig.problems];

  console.log("Runtime — server surface (D-224)");
  console.log(renderTable(rowsFor(runtime.runtime, runtime.sources)));
  console.log("");
  console.log("Public — client surface (build time only)");
  console.log(renderTable(rowsFor(publicConfig.public, publicConfig.sources)));

  if (problems.length > 0) {
    console.error(formatRuntimeProblems(problems));
    return 1;
  }
  return 0;
}

try {
  process.exitCode = await main(process.argv.slice(2));
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`[facilis:env] ${message}`);
  console.error(USAGE);
  process.exitCode = 1;
}
